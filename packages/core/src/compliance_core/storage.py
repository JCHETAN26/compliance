"""File storage interface and the local-volume implementation.

Keys are generated by the server (never from user filenames), validated against a
strict pattern, and resolved paths must stay inside the storage root. Writes are atomic:
files are staged inside the root and renamed into place.
"""

from __future__ import annotations

import os
import re
import shutil
import tempfile
import uuid
from pathlib import Path
from typing import BinaryIO, Protocol

_KEY = re.compile(r"^[a-z0-9][a-z0-9_-]*(?:/[a-z0-9][a-z0-9_-]*){0,6}$")


class StorageError(Exception):
    pass


class Storage(Protocol):
    def new_staging_file(self) -> Path: ...

    def put(self, key: str, staged: Path) -> None: ...

    def open(self, key: str) -> BinaryIO: ...

    def local_path(self, key: str) -> Path: ...

    def size(self, key: str) -> int: ...

    def exists(self, key: str) -> bool: ...

    def delete(self, key: str) -> None: ...


def document_key(workspace_id: uuid.UUID, document_id: uuid.UUID) -> str:
    return f"documents/{workspace_id.hex}/{document_id.hex}/original"


class LocalStorage:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()
        self._staging = self.root / ".staging"
        self._staging.mkdir(parents=True, exist_ok=True, mode=0o750)

    def _path(self, key: str) -> Path:
        if not _KEY.match(key):
            raise StorageError(f"invalid storage key {key!r}")
        path = (self.root / key).resolve()
        if self.root not in path.parents:
            raise StorageError("storage key escapes the storage root")
        return path

    def new_staging_file(self) -> Path:
        fd, name = tempfile.mkstemp(prefix="upload-", dir=self._staging)
        os.close(fd)
        return Path(name)

    def put(self, key: str, staged: Path) -> None:
        target = self._path(key)
        target.parent.mkdir(parents=True, exist_ok=True, mode=0o750)
        staged_resolved = staged.resolve()
        if staged_resolved.parent == self._staging:
            os.chmod(staged_resolved, 0o640)
            os.replace(staged_resolved, target)
            return
        # Source outside the staging area (e.g. seed files): copy, then atomic rename.
        tmp = self.new_staging_file()
        try:
            shutil.copyfile(staged, tmp)
            os.chmod(tmp, 0o640)
            os.replace(tmp, target)
        finally:
            tmp.unlink(missing_ok=True)

    def open(self, key: str) -> BinaryIO:
        try:
            return self._path(key).open("rb")
        except FileNotFoundError as exc:
            raise StorageError(f"object {key!r} not found") from exc

    def local_path(self, key: str) -> Path:
        path = self._path(key)
        if not path.is_file():
            raise StorageError(f"object {key!r} not found")
        return path

    def size(self, key: str) -> int:
        return self.local_path(key).stat().st_size

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def delete(self, key: str) -> None:
        path = self._path(key)
        path.unlink(missing_ok=True)
        # Remove now-empty per-document directories, never the root itself.
        parent = path.parent
        while parent != self.root and parent.is_dir():
            try:
                parent.rmdir()
            except OSError:
                break
            parent = parent.parent
